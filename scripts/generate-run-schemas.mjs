#!/usr/bin/env node
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import TJS from "typescript-json-schema";
import { Ajv } from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function stableDefinitionNames(definitions) {
  // TJS uses TypeScript display names; NodeNext import qualifiers include the checkout path.
  // Normalize identifiers only, preserving the module suffix and every schema value.
  // TJS also strips spaces from display names, including spaces in that qualifier.
  const prefix = `import(${JSON.stringify(`${root}/`).slice(0, -1)}`.replaceAll(" ", "");
  const names = Object.fromEntries(
    Object.keys(definitions).map((name) => [name, name.replaceAll(prefix, 'import("')]),
  );
  if (new Set(Object.values(names)).size !== Object.keys(names).length) {
    throw new Error("Canonical schema definition names collide after path normalization.");
  }
  return names;
}

function stableSchema(schema, names, refs) {
  if (typeof schema === "boolean") {
    return schema;
  }
  const result = { ...schema };
  if (typeof schema.$ref === "string" && Object.hasOwn(refs, schema.$ref)) {
    result.$ref = refs[schema.$ref];
  }
  for (const key of ["definitions", "properties", "patternProperties", "dependencies"]) {
    if (schema[key] !== undefined) {
      result[key] = Object.fromEntries(
        Object.entries(schema[key]).map(([name, value]) => [
          key === "definitions" ? (names[name] ?? name) : name,
          Array.isArray(value) ? value : stableSchema(value, names, refs),
        ]),
      );
    }
  }
  for (const key of [
    "items",
    "additionalItems",
    "additionalProperties",
    "contains",
    "propertyNames",
    "if",
    "then",
    "else",
    "not",
    "allOf",
    "anyOf",
    "oneOf",
  ]) {
    const value = schema[key];
    if (value !== undefined) {
      result[key] = Array.isArray(value)
        ? value.map((entry) => stableSchema(entry, names, refs))
        : stableSchema(value, names, refs);
    }
  }
  return result;
}

function normalizeDefinitionPaths(schema) {
  const names = stableDefinitionNames(schema.definitions);
  const refs = Object.fromEntries(
    Object.entries(names).map(([name, stable]) => [
      `#/definitions/${encodeURIComponent(name)}`,
      `#/definitions/${encodeURIComponent(stable)}`,
    ]),
  );
  return stableSchema(schema, names, refs);
}

function standaloneValidators(schema, names) {
  const validator = new Ajv({
    strict: false,
    allErrors: true,
    strictNumbers: true,
    inlineRefs: false,
    code: { esm: true, source: true },
  });
  validator.addSchema(schema, "run");
  const refs = Object.fromEntries(
    names.map((name) => [
      name,
      name === "SupervisorQuestionView"
        ? "run#/definitions/SupervisorQuestionView/properties/revival"
        : `run#/definitions/${name}`,
    ]),
  );
  for (const [name, ref] of Object.entries(refs)) {
    validator.addSchema({ $ref: ref }, name);
  }
  return `// Generated by scripts/generate-run-schemas.mjs; do not edit.\n${standaloneCode(validator, Object.fromEntries(names.map((name) => [name, name])))}\n`;
}

function validatorDeclarations(names) {
  const types = {
    SubagentRunConfig: "SubagentRunConfig",
    NativeFinalizationConfig: "NativeFinalizationConfig",
    NativeFinalizationEvent: "NativeFinalizationEvent",
    SupervisorQuestionView: 'NonNullable<Run.SupervisorQuestionView["revival"]>',
  };
  return [
    "// Generated by scripts/generate-run-schemas.mjs; do not edit.",
    'import type { ValidateFunction } from "ajv";',
    'import type * as Run from "../src/shared/types.ts";',
    'import type { SubagentRunConfig } from "../src/runs/background/runner-config.ts";',
    'import type { NativeFinalizationConfig, NativeFinalizationEvent } from "../src/runs/shared/native-finalization-types.ts";',
    ...names.map(
      (name) => `export const ${name}: ValidateFunction<${types[name] ?? `Run.${name}`}>;`,
    ),
    "",
  ].join("\n");
}

function publishArtifact(target, content, mode) {
  if (mode !== "--check") {
    fs.writeFileSync(target, content);
    return;
  }
  if (fs.readFileSync(target, "utf8") !== content) {
    throw new Error(`Stale ${path.basename(target)}. Run node scripts/generate-run-schemas.mjs.`);
  }
}

const mode = process.argv[2];
if (mode === "--help" || mode === "-h") {
  console.log(
    "Usage: node scripts/generate-run-schemas.mjs [--check]\nGenerate runtime JSON schemas and standalone validators from canonical persisted run types.\nExamples:\n  node scripts/generate-run-schemas.mjs\n  node scripts/generate-run-schemas.mjs --check",
  );
} else {
  if (mode !== undefined && mode !== "--check") {
    throw new Error(`Unknown argument: ${mode}`);
  }
  const inputs = [
    "src/shared/types/async.ts",
    "src/shared/types/owned-runs.ts",
    "src/shared/types/questions.ts",
    "src/shared/types/history.ts",
    "src/shared/types/details.ts",
    "src/runs/background/runner-config.ts",
    "src/runs/shared/native-finalization-types.ts",
  ].map((file) => path.join(root, file));
  const program = TJS.getProgramFromFiles(
    inputs,
    {
      strict: true,
      noImplicitReturns: true,
      skipLibCheck: true,
      target: "ESNext",
      lib: ["ESNext"],
      module: "NodeNext",
      moduleResolution: "NodeNext",
      allowImportingTsExtensions: true,
      resolveJsonModule: true,
    },
    root,
  );
  const generator = TJS.buildGenerator(program, {
    required: true,
    aliasRef: true,
    defaultNumberType: "number",
  });
  if (generator === null) {
    throw new Error("Canonical run types could not be compiled for schema generation.");
  }
  const names = [
    "AsyncStatus",
    "AsyncResultFile",
    "ForegroundResumeRun",
    "OwnedRun",
    "AsyncStartedEvent",
    "ControlEvent",
    "SupervisorRunContract",
    "SupervisorQuestion",
    "QuestionAnswer",
    "QuestionDelivery",
    "SupervisorQuestionView",
    "HistoryRunRow",
    "HistoryRunPage",
    "HistoryPage",
    "HistorySearchPage",
    "HistoryIndexStatus",
    "HistoryEntry",
    "HistoryResult",
    "Details",
    "SubagentExecutionResult",
    "SubagentRunConfig",
    "NativeFinalizationConfig",
    "NativeFinalizationEvent",
  ];
  const schema = normalizeDefinitionPaths(generator.getSchemaForSymbols(names));
  const artifacts = {
    "src/runs/background/schemas/RunContracts.json": `${JSON.stringify(schema, null, 2)}\n`,
    "generated/RunValidators.js": standaloneValidators(schema, names),
    "generated/RunValidators.d.ts": validatorDeclarations(names),
  };
  fs.mkdirSync(path.join(root, "generated"), { recursive: true });
  for (const [name, content] of Object.entries(artifacts)) {
    publishArtifact(path.join(root, name), content, mode);
  }
  console.log(
    `${mode === "--check" ? "Verified" : "Generated"} ${names.length} canonical run schemas and standalone validators.`,
  );
}
